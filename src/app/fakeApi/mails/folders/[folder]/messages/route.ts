export async function GET(
  request: Request,
  { params }: { params: { folder: string } }
) {
  const { folder } = await params
  const { searchParams } = new URL(request.url)
  const filter = searchParams.get('filter') || undefined
  const pageParam = searchParams.get('page')
  const page = pageParam ? parseInt(pageParam, 10) : 1

  let messages: ImapMessagesList[] = messagesByFolder[folder] || []

  switch (filter) {
    case 'starred':
      messages = messages.filter((msg) => msg.flagged)
      break
    case 'attachments':
      messages = messages.filter((msg) => msg.hasAttachment)
      break
    case 'read':
      messages = messages.filter((msg) => msg.seen)
      break
    case 'unread':
      messages = messages.filter((msg) => !msg.seen)
      break
  }

  const pageSize = 20
  const start = (page - 1) * pageSize
  const end = start + pageSize
  const pagedMessages = messages.slice(start, end)

  const totalPages = Math.ceil(messages.length / pageSize)

  return NextResponse.json({
    messages: pagedMessages,
    total: messages.length,
    page,
    pageSize,
    totalPages,
    hasNextPage: page < totalPages,
    hasPreviousPage: page > 1,
  })
}

export async function OPTIONS() {
  return NextResponse.json({ allow: ['GET'] }, { status: 200 })
}
